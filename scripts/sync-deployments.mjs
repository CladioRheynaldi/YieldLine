// Copies deployment records written by DeployYieldLine.s.sol into @yieldline/shared.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "packages", "shared", "src", "generated", "deployments.ts");

const networks = { arbitrumSepolia: "arbitrum-sepolia.json", anvil: "anvil.json" };
const keys = [
  "deployer",
  "mockUSDC",
  "mockTBILL",
  "complianceRegistry",
  "mockOracle",
  "oracleAdapter",
  "registry",
  "riskEngine",
  "liquidityVault",
  "creditVault",
];

let source = "// Generated by scripts/sync-deployments.mjs. Do not edit.\n";
source += 'import type { DeploymentRecord } from "../deployments";\n';
for (const [name, file] of Object.entries(networks)) {
  const path = join(root, "deployments", file);
  if (!existsSync(path)) {
    source += `\nexport const ${name}Record: DeploymentRecord | null = null;\n`;
    continue;
  }
  const record = JSON.parse(readFileSync(path, "utf8"));
  const lines = [`  chainId: ${Number(record.chainId)},`];
  lines.push(`  deploymentBlock: ${record.deploymentBlock == null ? "null" : `${BigInt(record.deploymentBlock)}n`},`);
  for (const key of keys) lines.push(`  ${key}: ${record[key] ? JSON.stringify(record[key]) : "null"},`);
  source += `\nexport const ${name}Record: DeploymentRecord | null = {\n${lines.join("\n")}\n};\n`;
  console.log(`Synced ${file}`);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, source);
